def make_isbn(i):
    """A well-formed, checksum-valid ISBN-13 under the real 978 (Bookland)
    prefix — deterministic and unique per book, not a real catalog lookup,
    but structurally a genuine, valid ISBN-13."""
    first12 = f"978{100000000 + i * 9973 % 899999999:09d}"
    total = sum((1 if idx % 2 == 0 else 3) * int(d) for idx, d in enumerate(first12))
    check_digit = (10 - (total % 10)) % 10
    return first12 + str(check_digit)

