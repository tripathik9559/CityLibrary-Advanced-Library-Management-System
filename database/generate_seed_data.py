# loans can belong to any student status (a since-blocked/inactive member may
# well have borrowed-and-returned books while still active).
active_student_idxs = [i for i, s in enumerate(students) if s["status"] == "active"]

# Category popularity weighting -> how many historical loans each book tends
# to attract (bestsellers / core textbooks get borrowed far more than a
# single-copy philosophy dialogue).
POPULARITY = {
    CS: 1.3, MA: 0.8, PH: 0.7, LI: 1.4, BI: 1.0,
    HI: 0.9, BE: 1.3, SH: 1.5, EL: 0.7, PL: 0.5,
}
book_weights = [POPULARITY[b[1]] * b[8] / 5.0 for b in book_rows]  # also scale a bit by copy count

# Student engagement weighting -> a minority of members borrow much more than
# the rest (realistic power-law-ish usage), independent of current status.
student_weights = [random.choice([1, 1, 1, 2, 2, 3, 5]) for _ in students]

ADMIN_IDS = [1, 2]

# Track concurrently-active (unreturned) loans per book/student so we never
# violate available_copies or the 3-books-per-active-student rule.
active_count_per_book = [0] * len(book_rows)
active_count_per_student = [0] * len(students)

emit("-- ---------------------------------------------------------------------\n"
     "-- Book Issues (500) + Fine Payments\n"
     "-- Historical returned loans are written as INSERT (status='issued')\n"
     "-- immediately followed by an UPDATE to status='returned', mirroring\n"
     "-- exactly what sp_issue_book + sp_return_book would produce -- so\n"
     "-- available_copies is maintained purely by the existing triggers,\n"
     "-- with zero drift and no reconciliation step required.\n"
     "-- ---------------------------------------------------------------------")

def pick_book():
    return random.choices(range(len(book_rows)), weights=book_weights, k=1)[0]


def pick_student(active_only=False):
    pool = active_student_idxs if active_only else range(len(students))
    weights = [student_weights[i] for i in pool]
    return random.choices(list(pool), weights=weights, k=1)[0]


issue_rows = []  # for summary stats only

# --- Historical, already-returned loans (450) ------------------------------
# Spread issue_date over the last ~20 months with a mild recency bias.
SPAN_DAYS = 610
for n in range(HISTORICAL_RETURNED):
    b_idx = pick_book()
    s_idx = pick_student(active_only=False)

    days_ago = int(random.triangular(20, SPAN_DAYS, 90))  # more mass toward "more recent"
    issue_date = TODAY - timedelta(days=days_ago)
    loan_days = random.choice([7, 14, 14, 14, 21])
    due_date = issue_date + timedelta(days=loan_days)

    # 65% on-time-or-early, 35% late (by 1-45 days)
    if random.random() < 0.65:
        return_offset = random.randint(-5, 0)
    else:
        return_offset = random.randint(1, 45)
    return_date = due_date + timedelta(days=return_offset)
    if return_date > TODAY:
        return_date = TODAY

    issued_by = random.choice(ADMIN_IDS)
    returned_to = random.choice(ADMIN_IDS)

    emit(
        f"INSERT INTO book_issues (book_id, student_id, issue_date, due_date, issued_by, status) "
        f"VALUES ({b_idx + 1}, {s_idx + 1}, '{issue_date.isoformat()}', '{due_date.isoformat()}', {issued_by}, 'issued');"
    )
    emit("SET @iid := LAST_INSERT_ID();")
    emit(
        f"UPDATE book_issues SET return_date = '{return_date.isoformat()}', status = 'returned', "
        f"returned_to = {returned_to}, fine_amount = fn_calculate_fine(due_date, '{return_date.isoformat()}') "
        f"WHERE issue_id = @iid;"
    )
    issue_rows.append({"late": return_offset > 0})

# --- Currently active loans (50) -------------------------------------------
for n in range(CURRENTLY_ISSUED_OK):
    # find a book/student with headroom
    for _ in range(50):
        b_idx = pick_book()
        if active_count_per_book[b_idx] < book_rows[b_idx][8]:
            break
    for _ in range(50):
        s_idx = pick_student(active_only=True)
        if active_count_per_student[s_idx] < 3:
            break
    active_count_per_book[b_idx] += 1
    active_count_per_student[s_idx] += 1

    days_in = random.randint(1, 10)
    issue_date = TODAY - timedelta(days=days_in)
    loan_days = random.choice([7, 14, 14, 21])
    due_date = issue_date + timedelta(days=loan_days)
    if due_date <= TODAY:
        due_date = TODAY + timedelta(days=random.randint(1, 7))
    issued_by = random.choice(ADMIN_IDS)

    emit(
        f"INSERT INTO book_issues (book_id, student_id, issue_date, due_date, issued_by, status) "
        f"VALUES ({b_idx + 1}, {s_idx + 1}, '{issue_date.isoformat()}', '{due_date.isoformat()}', {issued_by}, 'issued');"
    )

for n in range(CURRENTLY_OVERDUE):
    for _ in range(50):
        b_idx = pick_book()
        if active_count_per_book[b_idx] < book_rows[b_idx][8]:
            break
    for _ in range(50):
        s_idx = pick_student(active_only=True)
        if active_count_per_student[s_idx] < 3:
            break
    active_count_per_book[b_idx] += 1
    active_count_per_student[s_idx] += 1

    days_overdue = random.randint(1, 25)
    loan_days = random.choice([7, 14, 21])
    due_date = TODAY - timedelta(days=days_overdue)
    issue_date = due_date - timedelta(days=loan_days)
    issued_by = random.choice(ADMIN_IDS)

    emit(
        f"INSERT INTO book_issues (book_id, student_id, issue_date, due_date, issued_by, status) "
        f"VALUES ({b_idx + 1}, {s_idx + 1}, '{issue_date.isoformat()}', '{due_date.isoformat()}', {issued_by}, 'overdue');"
    )

emit("")
emit("-- ---------------------------------------------------------------------")
emit("-- Fine collection: deterministic split over every returned-late issue")
emit("-- (fine_amount > 0), by MOD(issue_id, 10):")
emit("--   0-5 (60%) -> fully paid      6-7 (20%) -> partially paid      8-9 (20%) -> unpaid")
emit("-- ---------------------------------------------------------------------")
emit("""
UPDATE book_issues
   SET fine_paid = 1
 WHERE fine_amount > 0
   AND MOD(issue_id, 10) IN (0,1,2,3,4,5);

INSERT INTO fine_payments (issue_id, amount_paid, collected_by)
SELECT issue_id, fine_amount, returned_to
FROM book_issues
WHERE fine_paid = 1 AND fine_amount > 0;

-- Partial payments: pay roughly 40% of the fine, leave fine_paid = 0
INSERT INTO fine_payments (issue_id, amount_paid, collected_by)
SELECT issue_id, ROUND(fine_amount * 0.4, 2), returned_to
FROM book_issues
WHERE fine_amount > 0
  AND fine_paid = 0
  AND MOD(issue_id, 10) IN (6,7);

-- (MOD(issue_id,10) IN (8,9) rows are left fine_paid = 0 with no payment
-- row at all -- fully unpaid fines.)
""")

late_count = sum(1 for r in issue_rows if r["late"])
print(f"generated {TOTAL_ISSUES} book_issues "
      f"({HISTORICAL_RETURNED} returned [{late_count} late / {HISTORICAL_RETURNED - late_count} on-time], "
      f"{CURRENTLY_ISSUED_OK} currently issued, {CURRENTLY_OVERDUE} currently overdue)")

