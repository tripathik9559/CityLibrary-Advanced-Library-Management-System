"""
Generates database/06_seed_data.sql — a large, realistic sample dataset
for the Library Management System.

This script does NOT touch schema/views/functions/procedures/triggers.
It only emits plain SQL (INSERT/UPDATE statements using the existing
schema and calling the existing fn_calculate_fine() function) that
loads through the normal database/01-05 scripts unchanged.

Design notes on how historical circulation history is seeded safely:
  - trg_before_issue_insert blocks any INSERT into book_issues once a
    book's available_copies hits 0, and trg_after_issue_insert
    decrements available_copies on every insert regardless of the
    row's status. To avoid exhausting a book's stock while seeding
    hundreds of *already-returned* historical loans, each historical
    "returned" record is written the same way the real app would
    produce it: INSERT as status='issued' (decrements stock), then
    immediately UPDATE to status='returned' (trg_after_return_update
    restocks it). Net effect on available_copies is zero, exactly like
    a real issue+return cycle — no reconciliation hack needed.
  - fine_amount for returned rows is computed by the UPDATE statement
    itself via fn_calculate_fine(due_date, return_date) — the same
    function the real sp_return_book procedure uses — so the seed data
    is guaranteed consistent with the live business logic.
  - fine_paid / fine_payments are assigned afterwards with a
    deterministic MOD(issue_id, 10) bucket over rows where
    fine_amount > 0, so re-running this generator always produces the
    same paid/partial/unpaid mix.

Run:  python3 generate_seed_data.py > 06_seed_data.sql
"""
